export function randomNickname(rng: () => number): string {
  const roll = rng();
  if (roll < 0.35) {
    const a = NICK_ADJECTIVES[Math.floor(rng() * NICK_ADJECTIVES.length)]!;
    const n = NICK_NOUNS[Math.floor(rng() * NICK_NOUNS.length)]!;
    const num = 1 + Math.floor(rng() * 99);
    return `${a}_${n}${num}`;
  }
  if (roll < 0.65) {
    const w = ["tanusha", "marina", "igor", "oleg", "kate", "dima", "sveta", "pasha", "nastya", "misha"][
      Math.floor(rng() * 10)
    ]!;
    return `${w}${Math.floor(rng() * 900 + 10)}`;
  }
  const parts = ["neo", "sky", "mix", "pro", "tip", "bar", "msk", "spb", "kzn", "nsk"];
  return `${parts[Math.floor(rng() * parts.length)]!}_${parts[Math.floor(rng() * parts.length)]!}${Math.floor(rng() * 99)}`;
}

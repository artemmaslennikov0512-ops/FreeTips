export function buildSavingGoals(count: number, rng: () => number): string[] {
  const goals: string[] = [];
  const seen = new Set<string>();
  let i = 0;
  while (goals.length < count) {
    const v = GOAL_VERBS[Math.floor(rng() * GOAL_VERBS.length)]!;
    const t = GOAL_TARGETS[Math.floor(rng() * GOAL_TARGETS.length)]!;
    const e = GOAL_EXTRA[Math.floor(rng() * GOAL_EXTRA.length)]!;
    const nudge = i % 17 === 0 ? ` (${2024 + (i % 3)} год)` : "";
    let g = `${v} ${t}${nudge}.${e}`.replace(/\.\./g, ".").trim();
    if (g.length > 500) g = g.slice(0, 497) + "...";
    if (!seen.has(g)) {
      seen.add(g);
      goals.push(g);
    }
    i += 1;
    if (i > count * 80) break;
  }
  while (goals.length < count) {
    goals.push(`Коплю на личные цели (${goals.length + 1}). Часть суммы — с чаевых после смен.`);
  }
  return goals.slice(0, count);
}


/** ≥450 уникальных должностей (не «Официант»). */
export function buildNonWaiterJobTitles(): string[] {
  const set = new Set<string>();
  for (const b of JOB_BASES) {
    for (const v of JOB_VENUES) {
      for (const m of JOB_MODS) {
        const s = `${b}${m} ${v}`.trim();
        if (s.length <= 120) set.add(s);
      }
    }
  }
  const arr = [...set];
  if (arr.length < 450) {
    let k = 0;
    while (arr.length < 460) {
      k += 1;
      arr.push(`Специалист гостевого сервиса (смена ${k})`);
    }
  }
  return arr.slice(0, 460);
}

